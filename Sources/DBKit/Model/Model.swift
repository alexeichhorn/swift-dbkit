import PostgresNIO

/// A table-backed model. Conform with `@Model`, which generates every requirement.
///
/// `Base` is the model class itself, the plain row that queries return.
public protocol Model: Sendable {
    associatedtype Base: Model where Base.Base == Base
    /// The values needed to insert a row: every column except auto-increment keys.
    associatedtype Insert: ModelInsert

    static var schema: Schema { get }
    static func decodeBase(from row: RowReader) throws -> Base

    /// Every column with its current value, in schema order.
    var columnValues: [ColumnValue] { get }
}

/// Generated `Model.Insert` types.
public protocol ModelInsert: Sendable {
    var columnValues: [ColumnValue] { get }
}

/// Table metadata generated by `@Model`.
public struct Schema: Sendable {
    public let table: String
    public let columns: [String]
    public let primaryKey: [String]

    public init(table: String, columns: [String], primaryKey: [String]) {
        self.table = table
        self.columns = columns
        self.primaryKey = primaryKey
    }
}

/// A column name with a value to write.
public struct ColumnValue: Sendable {
    public let column: String
    public let node: SQLNode

    public init(_ column: String, _ value: some SQLType) {
        self.column = column
        self.node = value.sqlNode
    }

    init(column: String, node: SQLNode) {
        self.column = column
        self.node = node
    }
}

/// Reads model columns from a result row.
public struct RowReader {
    let row: PostgresRandomAccessRow

    public func decode<V: SQLType>(_ type: V.Type, _ column: String) throws -> V {
        guard row.contains(column) else { throw DBKitError.missingColumn(column) }
        do {
            return try V.decode(from: row[column])
        } catch {
            throw DBKitError.decodingFailed(column: column, type: "\(V.self)")
        }
    }
}

extension Model {
    /// Starts a `SELECT` for this model's table.
    public static func query() -> Query<Base> { Query() }

    public static func insert(_ values: Base.Insert) -> InsertQuery<Base> { InsertQuery(rows: [values.columnValues]) }

    /// Inserts several rows with one multi-row `INSERT`.
    public static func insert(_ values: [Base.Insert]) -> InsertQuery<Base> { InsertQuery(rows: values.map(\.columnValues)) }

    public static func update() -> UpdateQuery<Base> { UpdateQuery() }

    public static func delete() -> DeleteQuery<Base> { DeleteQuery() }

    /// Deletes this row by primary key. Returns the number of deleted rows.
    @discardableResult
    public func delete(on executor: some DatabaseExecutor) async throws -> Int {
        try await Base.delete().filtered(primaryKeyPredicate).execute(on: executor)
    }

    var primaryKeyPredicate: SQLNode {
        let values = columnValues
        let predicates = Self.schema.primaryKey.map { column in
            let value = values.first { $0.column == column }!.node
            let reference = SQLNode.column(ColumnReference(table: Self.schema.table, name: column))
            return SQLNode.infix(reference, "=", value, parenthesized: false)
        }
        return predicates.dropFirst().reduce(predicates[0]) { .infix($0, "AND", $1) }
    }
}
