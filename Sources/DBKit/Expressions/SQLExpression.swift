/// Anything usable as a typed SQL operand: plain values (`"text"`, `42`) and expressions.
public protocol SQLArgument<Value>: Sendable {
    associatedtype Value: SQLType
    var sqlNode: SQLNode { get }
}

/// A typed SQL expression: columns, function calls, operator results.
///
/// Plain Swift values are deliberately not expressions, so DBKit's operators never interfere with ordinary
/// Swift arithmetic or comparisons.
public protocol SQLExpression<Value>: SQLArgument {}

/// A type-erased expression producing `Value`.
public struct Expr<Value>: Sendable {
    public let sqlNode: SQLNode

    public init(_ sqlNode: SQLNode) {
        self.sqlNode = sqlNode
    }
}

// Conditional so results like `Expr<L.Value.AsBool>` can be spelled generically; every concrete result type is a
// `SQLType`.
extension Expr: SQLArgument, SQLExpression where Value: SQLType {
    /// Wraps a Swift value as an expression, for the rare places that need an expression on both sides.
    public static func value(_ value: Value) -> Expr<Value> {
        Expr(value.sqlNode)
    }
}

/// A column of `Model`'s table. Generated by `@Model` as a static property per stored property.
public struct Column<Model: DBKit.Model, Value: SQLType>: SQLExpression {
    public let name: String
    let read: @Sendable (Model) -> Value

    public init(_ name: String, _ read: @escaping @Sendable (Model) -> Value) {
        self.name = name
        self.read = read
    }

    public var sqlNode: SQLNode { .column(ColumnReference(table: Model.schema.table, name: name)) }
}

/// An aggregate function call. Only aggregates accept a `FILTER (WHERE …)` clause.
public struct AggregateExpr<Value: SQLType>: SQLExpression {
    public let sqlNode: SQLNode

    init(_ sqlNode: SQLNode) {
        self.sqlNode = sqlNode
    }

    /// Restricts the rows this aggregate sees: `COUNT(x) FILTER (WHERE …)`. PostgreSQL takes one filter, right after
    /// the aggregate call, so the result is a plain expression without `filter`.
    public func filter<P: SQLExpression>(_ predicate: P) -> Expr<Value> where P.Value.NonNull == Bool {
        Expr(.sequence([sqlNode, .raw(" FILTER (WHERE "), predicate.sqlNode, .raw(")")]))
    }
}

/// A sort key for `orderBy`.
public struct OrderBy: Sendable {
    let node: SQLNode
    let descending: Bool
}

extension SQLExpression {
    public var asc: OrderBy { OrderBy(node: sqlNode, descending: false) }
    public var desc: OrderBy { OrderBy(node: sqlNode, descending: true) }

    /// Names a projected expression: `SELECT expr AS "alias"`.
    public func `as`(_ alias: String) -> Aliased<Value> {
        Aliased(node: sqlNode, alias: alias)
    }
}

/// A projected expression with a column alias.
public struct Aliased<Value: SQLType>: Sendable {
    let node: SQLNode
    let alias: String
}
