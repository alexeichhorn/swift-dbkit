/// Anything usable as a typed SQL operand: plain values (`"text"`, `42`) and expressions.
public protocol SQLArgument<Value>: Sendable {
    associatedtype Value: SQLType
    var sqlNode: SQLNode { get }
}

/// A typed SQL expression: columns, operator results.
///
/// Plain Swift values are deliberately not expressions, so DBKit's operators never interfere with ordinary
/// Swift arithmetic or comparisons.
public protocol SQLExpression<Value>: SQLArgument {}

/// A type-erased expression producing `Value`.
public struct Expr<Value: SQLType>: SQLExpression {
    public let sqlNode: SQLNode

    public init(_ sqlNode: SQLNode) {
        self.sqlNode = sqlNode
    }
}

/// A column of `Model`'s table. Generated by `@Model` as a static property per stored property.
public struct Column<Model: DBKit.Model, Value: SQLType>: SQLExpression {
    public let name: String

    public init(_ name: String) {
        self.name = name
    }

    public var sqlNode: SQLNode { .column(ColumnReference(table: Model.schema.table, name: name)) }
}

/// A sort key for `orderBy`.
public struct OrderBy: Sendable {
    let node: SQLNode
    let descending: Bool
}

extension SQLExpression {
    public var asc: OrderBy { OrderBy(node: sqlNode, descending: false) }
    public var desc: OrderBy { OrderBy(node: sqlNode, descending: true) }
}
